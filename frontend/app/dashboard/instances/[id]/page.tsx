"use client";

import { useEffect, useState } from "react";
import { useParams } from "next/navigation";
import { useRequireAuth } from "@/hooks/useRequireAuth";
import { DashboardShell } from "@/components/DashboardShell";
import { instancesApi, ApiError } from "@/services/api";
import type { OnboardingInstance } from "@/types/api";

export default function InstanceDetailPage() {
  const { id } = useParams<{ id: string }>();
  const { user, loading, logout } = useRequireAuth();

  const [instance, setInstance] = useState<OnboardingInstance | null>(null);
  const [portalPath, setPortalPath] = useState<string | null>(null);
  const [liveStatus, setLiveStatus] = useState<unknown>(null);
  const [error, setError] = useState<string | null>(null);

  function refresh() {
    instancesApi.get(id).then(setInstance).catch(() => setError("Onboarding instance not found"));
    instancesApi.portalLink(id).then((r) => setPortalPath(r.portal_path));
  }

  useEffect(() => {
    if (!loading) refresh();
    const interval = setInterval(() => {
      if (!loading) refresh();
    }, 5000);
    return () => clearInterval(interval);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loading, id]);

  async function checkLiveWorkflow() {
    try {
      const r = await instancesApi.workflowStatus(id);
      setLiveStatus(r);
    } catch (err) {
      setLiveStatus({ error: err instanceof ApiError ? err.message : "Failed" });
    }
  }

  if (loading) return null;

  return (
    <DashboardShell user={user} onLogout={logout}>
      {error && <p className="text-sm text-destructive mb-4">{error}</p>}
      {instance && (
        <>
          <div className="flex items-center justify-between mb-6">
            <div>
              <h1 className="text-xl font-semibold">Onboarding {instance.id.slice(0, 8)}</h1>
              <p className="text-sm text-muted-foreground mt-1">
                Status: <span className="font-medium text-foreground">{instance.status}</span> · Step:{" "}
                {instance.current_step}
              </p>
            </div>
            {portalPath && (
              <a
                href={typeof window !== "undefined" ? `${window.location.origin}${portalPath}` : portalPath}
                target="_blank"
                rel="noreferrer"
                className="rounded-md border border-border px-3 py-1.5 text-sm hover:bg-secondary"
              >
                Open client portal ↗
              </a>
            )}
          </div>

          {instance.ai_intake_analysis && (
            <section className="rounded-lg border border-border p-4 mb-6">
              <div className="flex items-center justify-between mb-3">
                <h2 className="text-sm font-medium">AI Intake Summary</h2>
                <span
                  className={
                    "text-xs rounded-full px-2 py-0.5 " +
                    (instance.ai_intake_analysis.generated_by === "groq"
                      ? "bg-green-100 text-green-700"
                      : "bg-secondary text-muted-foreground")
                  }
                  title={
                    instance.ai_intake_analysis.generated_by === "groq"
                      ? "Generated by Groq"
                      : "Demo fallback — no GROQ_API_KEY configured"
                  }
                >
                  {instance.ai_intake_analysis.generated_by === "groq" ? "AI: Groq" : "AI: Demo fallback"}
                </span>
              </div>

              <p className="text-sm mb-4">{instance.ai_intake_analysis.client_overview}</p>

              <div className="grid sm:grid-cols-2 gap-4 text-sm">
                <div>
                  <h3 className="text-xs font-medium text-muted-foreground mb-1">Goals</h3>
                  <ul className="list-disc list-inside text-muted-foreground">
                    {instance.ai_intake_analysis.goals.length === 0 && <li>Not specified</li>}
                    {instance.ai_intake_analysis.goals.map((g, i) => (
                      <li key={i}>{g}</li>
                    ))}
                  </ul>
                </div>
                <div>
                  <h3 className="text-xs font-medium text-muted-foreground mb-1">Requested services</h3>
                  <ul className="list-disc list-inside text-muted-foreground">
                    {instance.ai_intake_analysis.requested_services.length === 0 && <li>Not specified</li>}
                    {instance.ai_intake_analysis.requested_services.map((s, i) => (
                      <li key={i}>{s}</li>
                    ))}
                  </ul>
                </div>
                <div>
                  <h3 className="text-xs font-medium text-muted-foreground mb-1">Key requirements</h3>
                  <ul className="list-disc list-inside text-muted-foreground">
                    {instance.ai_intake_analysis.key_requirements.length === 0 && <li>None noted</li>}
                    {instance.ai_intake_analysis.key_requirements.map((r, i) => (
                      <li key={i}>{r}</li>
                    ))}
                  </ul>
                </div>
                <div>
                  <h3 className="text-xs font-medium text-muted-foreground mb-1">Important details</h3>
                  <ul className="list-disc list-inside text-muted-foreground">
                    {instance.ai_intake_analysis.important_details.length === 0 && <li>None noted</li>}
                    {instance.ai_intake_analysis.important_details.map((d, i) => (
                      <li key={i}>{d}</li>
                    ))}
                  </ul>
                </div>
              </div>

              {instance.ai_intake_analysis.potential_concerns.length > 0 && (
                <div className="mt-4">
                  <h3 className="text-xs font-medium text-destructive mb-1">Potential concerns</h3>
                  <ul className="list-disc list-inside text-sm text-destructive">
                    {instance.ai_intake_analysis.potential_concerns.map((c, i) => (
                      <li key={i}>{c}</li>
                    ))}
                  </ul>
                </div>
              )}
            </section>
          )}

          {instance.missing_info && (
            <section className="rounded-lg border border-border p-4 mb-6">
              <div className="flex items-center justify-between mb-3">
                <h2 className="text-sm font-medium">Missing Information</h2>
                <span className="text-xs text-muted-foreground">{instance.missing_info.progress_percent}% complete</span>
              </div>
              {instance.missing_info.missing_fields.length === 0 && instance.missing_info.missing_documents.length === 0 ? (
                <p className="text-sm text-green-600">Nothing missing — all required fields and documents are in.</p>
              ) : (
                <div className="grid sm:grid-cols-2 gap-4 text-sm">
                  {instance.missing_info.missing_fields.length > 0 && (
                    <div>
                      <h3 className="text-xs font-medium text-muted-foreground mb-1">Missing required fields</h3>
                      <ul className="flex flex-col gap-1">
                        {instance.missing_info.missing_fields.map((f, i) => (
                          <li key={i} className="text-destructive">
                            ⚠ {f}
                          </li>
                        ))}
                      </ul>
                    </div>
                  )}
                  {instance.missing_info.missing_documents.length > 0 && (
                    <div>
                      <h3 className="text-xs font-medium text-muted-foreground mb-1">Missing required documents</h3>
                      <ul className="flex flex-col gap-1">
                        {instance.missing_info.missing_documents.map((d, i) => (
                          <li key={i} className="text-destructive">
                            ⚠ {d}
                          </li>
                        ))}
                      </ul>
                    </div>
                  )}
                </div>
              )}
            </section>
          )}

          <div className="grid sm:grid-cols-2 gap-6 mb-8">
            <section className="rounded-lg border border-border p-4">
              <h2 className="text-sm font-medium mb-3">Documents</h2>
              {instance.document_requests.length === 0 && (
                <p className="text-sm text-muted-foreground">No documents required for this template.</p>
              )}
              <ul className="flex flex-col gap-3">
                {instance.document_requests.map((req) => (
                  <li key={req.id} className="text-sm">
                    <div className="flex items-center justify-between">
                      <span>{req.name}</span>
                      <span className="text-muted-foreground">{req.status}</span>
                    </div>
                    {req.documents.map((doc) => (
                      <div key={doc.id} className="ml-3 mt-1 text-xs text-muted-foreground">
                        {doc.original_filename} — confidence {doc.ai_confidence ?? "…"} —{" "}
                        <span
                          className={doc.review_status === "NEEDS_REVIEW" ? "text-destructive" : "text-green-600"}
                        >
                          {doc.review_status}
                        </span>
                      </div>
                    ))}
                  </li>
                ))}
              </ul>
            </section>

            <section className="rounded-lg border border-border p-4">
              <h2 className="text-sm font-medium mb-3">Account connections</h2>
              {instance.integration_accounts.length === 0 && (
                <p className="text-sm text-muted-foreground">Awaiting client action.</p>
              )}
              <ul className="flex flex-col gap-2 text-sm">
                {instance.integration_accounts.map((acc) => (
                  <li key={acc.provider} className="flex items-center justify-between">
                    <span>{acc.provider}</span>
                    <span className={acc.status === "CONNECTED" ? "text-green-600" : "text-muted-foreground"}>
                      {acc.status}
                    </span>
                  </li>
                ))}
              </ul>
            </section>
          </div>

          {instance.kickoff_brief && (
            <section className="rounded-lg border border-border p-4 mb-8">
              <h2 className="text-sm font-medium mb-3">AI-generated kickoff brief</h2>
              <pre className="text-xs whitespace-pre-wrap text-muted-foreground">
                {JSON.stringify(instance.kickoff_brief, null, 2)}
              </pre>
            </section>
          )}

          <section className="rounded-lg border border-border p-4">
            <div className="flex items-center justify-between mb-3">
              <h2 className="text-sm font-medium">Live Temporal workflow query</h2>
              <button
                onClick={checkLiveWorkflow}
                className="rounded-md border border-border px-3 py-1 text-xs hover:bg-secondary"
              >
                Query live workflow
              </button>
            </div>
            <p className="text-xs text-muted-foreground mb-2">
              This queries the running Temporal workflow directly (not just the mirrored DB fields), proving it&apos;s a
              live process, not just a database row.
            </p>
            {liveStatus !== null && (
              <pre className="text-xs whitespace-pre-wrap text-muted-foreground">
                {JSON.stringify(liveStatus, null, 2)}
              </pre>
            )}
          </section>
        </>
      )}
    </DashboardShell>
  );
}
